#Classe Dataset
class PetSegmentationDataset(Dataset):

    def __init__(self, root='.', split='train', img_size=256):

        self.root = root
        self.img_size = img_size

        self.img_transform = transforms.Compose([
            transforms.Resize((img_size,img_size)),
            transforms.ToTensor(),
            transforms.Normalize(
                [0.485,0.456,0.406],
                [0.229,0.224,0.225]
            )
        ])

        self.mask_transform = transforms.Compose([
            transforms.Resize(
                (img_size,img_size),
                interpolation=transforms.InterpolationMode.NEAREST
            )
        ])

        list_file = os.path.join(
            root,
            "annotations",
            "trainval.txt" if split=="train"
            else "test.txt"
        )

        with open(list_file) as f:
            self.names = [
                line.split()[0]
                for line in f.readlines()
            ]

    def __len__(self):
        return len(self.names)

    def __getitem__(self, idx):

        img = Image.open(
            os.path.join(
                self.root,
                "images",
                self.names[idx]+".jpg"
            )
        ).convert("RGB")

        mask = Image.open(
            os.path.join(
                self.root,
                "annotations",
                "trimaps",
                self.names[idx]+".png"
            )
        )

        img = self.img_transform(img)

        mask = torch.tensor(
            np.array(
                self.mask_transform(mask)
            ),
            dtype=torch.long
        ) - 1

        return img, mask

