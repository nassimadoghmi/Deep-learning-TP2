class SegmentationAugmentation:

    def __call__(self,image,mask):

        if random.random() > 0.5:

            image = TF.hflip(image)
            mask = TF.hflip(mask)

        angle = random.randint(
            -20,
            20
        )

        image = TF.rotate(
            image,
            angle
        )

        mask = TF.rotate(
            mask,
            angle
        )

        image = TF.adjust_brightness(
            image,
            random.uniform(
                0.8,
                1.2
            )
        )

        return image, mask

