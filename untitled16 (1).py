#TransferUNet
class TransferUNet(nn.Module):

    def __init__(
        self,
        num_classes=3,
        freeze_encoder=True
    ):

        super().__init__()

        backbone = resnet50(
            weights=ResNet50_Weights.IMAGENET1K_V2
        )

        self.enc0 = nn.Sequential(
            backbone.conv1,
            backbone.bn1,
            backbone.relu
        )

        self.pool = backbone.maxpool

        self.enc1 = backbone.layer1
        self.enc2 = backbone.layer2
        self.enc3 = backbone.layer3
        self.enc4 = backbone.layer4

        if freeze_encoder:

            for module in [
                self.enc0,
                self.enc1,
                self.enc2,
                self.enc3,
                self.enc4
            ]:

                for p in module.parameters():
                    p.requires_grad=False

        self.up4 = nn.ConvTranspose2d(
            2048,
            1024,
            2,
            stride=2
        )

        self.dec4 = ConvBlock(
            2048,
            512
        )

        self.up3 = nn.ConvTranspose2d(
            512,
            256,
            2,
            stride=2
        )

        self.dec3 = ConvBlock(
            768,
            256
        )

        self.up2 = nn.ConvTranspose2d(
            256,
            128,
            2,
            stride=2
        )

        self.dec2 = ConvBlock(
            384,
            64
        )

        self.up1 = nn.ConvTranspose2d(
            64,
            32,
            2,
            stride=2
        )

        self.dec1 = ConvBlock(
            96,
            32
        )

        self.final_up = nn.ConvTranspose2d(
            32,
            32,
            2,
            stride=2
        )

        self.out = nn.Conv2d(
            32,
            num_classes,
            1
        )

    def forward(self,x):

        e0 = self.enc0(x)

        e1 = self.enc1(
            self.pool(e0)
        )

        e2 = self.enc2(e1)

        e3 = self.enc3(e2)

        e4 = self.enc4(e3)

        d4 = self.up4(e4)
        d4 = torch.cat([d4,e3],dim=1)
        d4 = self.dec4(d4)

        d3 = self.up3(d4)
        d3 = torch.cat([d3,e2],dim=1)
        d3 = self.dec3(d3)

        d2 = self.up2(d3)
        d2 = torch.cat([d2,e1],dim=1)
        d2 = self.dec2(d2)

        d1 = self.up1(d2)
        d1 = torch.cat([d1,e0],dim=1)
        d1 = self.dec1(d1)

        d1 = self.final_up(d1)

        return self.out(d1)

