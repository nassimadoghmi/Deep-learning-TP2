#Q7 : Fonction IoU et Dice
def compute_iou_dice(pred_mask, true_mask, num_classes=3):

    iou_per_class = []
    dice_per_class = []

    for cls in range(num_classes):

        pred_cls = (pred_mask == cls)
        true_cls = (true_mask == cls)

        intersection = (pred_cls & true_cls).sum().item()

        union = (pred_cls | true_cls).sum().item()

        iou = intersection / (union + 1e-6)

        dice = (
            2 * intersection
        ) / (
            pred_cls.sum().item()
            + true_cls.sum().item()
            + 1e-6
        )

        iou_per_class.append(iou)
        dice_per_class.append(dice)

    mIoU = np.mean(iou_per_class)
    mDice = np.mean(dice_per_class)

    return mIoU, mDice, iou_per_class, dice_per_class

