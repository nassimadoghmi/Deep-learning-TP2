#Q5 : Score BLEU-4 sur le jeu de validation


def compute_bleu4(encoder, decoder, loader, vocab, device, beam=False):

    encoder.eval()
    decoder.eval()

    references  = []
    hypotheses  = []

    with torch.no_grad():

        for images, captions, _ in tqdm(loader, desc="BLEU-4"):

            for i in range(images.size(0)):

                img = images[i]

                if beam:
                    hyp = beam_search_caption(
                        encoder, decoder, img, vocab,
                        beam_size=3, device=device
                    )
                else:
                    hyp = greedy_caption(
                        encoder, decoder, img, vocab, device=device
                    )

                # Référence (caption GT de la batch)
                ref = [
                    vocab.itos.get(idx.item(), '<UNK>')
                    for idx in captions[i]
                    if idx.item() not in [
                        vocab.stoi['<PAD>'],
                        vocab.stoi['<SOS>'],
                        vocab.stoi['<EOS>']
                    ]
                ]

                references.append([ref])
                hypotheses.append(hyp.split())

    smooth = SmoothingFunction().method1
    bleu4  = corpus_bleu(references, hypotheses, smoothing_function=smooth)

    return bleu4


