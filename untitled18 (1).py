#Q5 : Greedy Search


def greedy_caption(encoder, decoder, image, vocab, max_len=50, device='cpu'):

    encoder.eval()
    decoder.eval()

    with torch.no_grad():

        feature = encoder(
            image.unsqueeze(0).to(device)
        )                                      # (1, embed_size)

        # Initialiser avec le token SOS
        inputs  = feature.unsqueeze(1)         # (1, 1, embed_size)
        hidden  = None
        words   = []

        for _ in range(max_len):

            out, hidden = decoder.lstm(inputs, hidden)

            logits      = decoder.fc(out.squeeze(1))
            pred        = logits.argmax(dim=-1)

            word = vocab.itos.get(pred.item(), '<UNK>')

            if word == '<EOS>':
                break

            if word not in ('<SOS>', '<PAD>'):
                words.append(word)

            inputs = decoder.embed(pred).unsqueeze(1)

    return ' '.join(words)

#Q5 : Beam Search


def beam_search_caption(
    encoder,
    decoder,
    image,
    vocab,
    beam_size = 3,
    max_len   = 50,
    device    = 'cpu'
):

    encoder.eval()
    decoder.eval()

    with torch.no_grad():

        feature = encoder(image.unsqueeze(0).to(device))  # (1, embed_size)

        # beams : (score, sequence, hidden_state)
        beams     = [(0.0, [vocab.stoi['<SOS>']], None)]
        completed = []

        for _ in range(max_len):

            new_beams = []

            for score, seq, hidden in beams:

                last_word = torch.tensor(
                    [[seq[-1]]]
                ).to(device)

                embed = decoder.embed(last_word)   # (1, 1, embed)

                if hidden is None:
                    inp = torch.cat(
                        [feature.unsqueeze(1), embed],
                        dim = 1
                    )
                    out, hidden = decoder.lstm(inp)
                    out = out[:, -1:]
                else:
                    out, hidden = decoder.lstm(embed, hidden)

                logprobs = F.log_softmax(
                    decoder.fc(out.squeeze(1)),
                    dim = -1
                )

                topk_scores, topk_ids = logprobs.topk(beam_size)

                for s, idx in zip(topk_scores[0], topk_ids[0]):

                    new_seq   = seq + [idx.item()]
                    new_score = score + s.item()

                    if idx.item() == vocab.stoi['<EOS>']:
                        completed.append(
                            (new_score / len(new_seq), new_seq)
                        )
                    else:
                        new_beams.append(
                            (
                                new_score,
                                new_seq,
                                (hidden[0].clone(), hidden[1].clone())
                            )
                        )

            beams = sorted(
                new_beams,
                key     = lambda x: x[0] / len(x[1]),
                reverse = True
            )[:beam_size]

            if not beams:
                break

        best = max(
            completed or [(0, beams[0][1])],
            key = lambda x: x[0]
        )

        return ' '.join([
            vocab.itos.get(i, '<UNK>')
            for i in best[1][1:-1]
        ])

