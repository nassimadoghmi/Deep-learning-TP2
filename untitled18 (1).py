# Q3 : ImageEncoder (ResNet50)


class ImageEncoder(nn.Module):

    def __init__(self, embed_size=256, fine_tune=False):

        super().__init__()

        resnet   = resnet50(weights=ResNet50_Weights.IMAGENET1K_V2)

        # Supprimer la tête de classification (garder jusqu'à layer4)
        modules  = list(resnet.children())[:-2]
        self.resnet = nn.Sequential(*modules)   # sortie : (B, 2048, 7, 7)

        self.adaptive_pool = nn.AdaptiveAvgPool2d((1, 1))
        self.fc            = nn.Linear(2048, embed_size)
        self.bn            = nn.BatchNorm1d(embed_size)

        # Geler les 6 premiers blocs, laisser libres les 2 derniers
        for param in list(self.resnet.parameters())[:int(len(list(self.resnet.parameters())) * 0.8)]:
            param.requires_grad = fine_tune

    def forward(self, images):

        features = self.resnet(images)                       # (B, 2048, 7, 7)
        features = self.adaptive_pool(features)              # (B, 2048, 1, 1)
        features = features.squeeze(-1).squeeze(-1)          # (B, 2048)
        features = self.bn(self.fc(features))                # (B, embed_size)

        return features

#Q3 : CaptionDecoder (LSTM)


class CaptionDecoder(nn.Module):

    def __init__(
        self,
        embed_size,
        hidden_size,
        vocab_size,
        num_layers = 2,
        dropout    = 0.5
    ):

        super().__init__()

        self.embed = nn.Embedding(
            vocab_size,
            embed_size,
            padding_idx = 0
        )

        self.lstm = nn.LSTM(
            embed_size,
            hidden_size,
            num_layers,
            batch_first = True,
            dropout     = dropout
        )

        self.fc      = nn.Linear(hidden_size, vocab_size)
        self.dropout = nn.Dropout(dropout)

    def forward(self, features, captions, lengths):

        # features : (B, embed_size) → premier token visuel
        embeddings = self.dropout(self.embed(captions[:, :-1]))

        # Concaténer le vecteur image comme premier token
        inputs = torch.cat(
            [features.unsqueeze(1), embeddings],
            dim = 1
        )

        # Pack pour ignorer le padding
        packed = nn.utils.rnn.pack_padded_sequence(
            inputs,
            lengths.cpu(),
            batch_first    = True,
            enforce_sorted = True
        )

        hiddens, _ = self.lstm(packed)

        hiddens, _ = nn.utils.rnn.pad_packed_sequence(
            hiddens,
            batch_first = True
        )

        return self.fc(hiddens)

