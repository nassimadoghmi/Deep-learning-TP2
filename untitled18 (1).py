class Vocabulary:

    def __init__(self, freq_threshold=5):

        self.freq_threshold = freq_threshold

        self.itos = {
            0: '<PAD>',
            1: '<SOS>',
            2: '<EOS>',
            3: '<UNK>'
        }

        self.stoi = {v: k for k, v in self.itos.items()}

    def __len__(self):
        return len(self.itos)

    @staticmethod
    def tokenize(text):
        return re.findall(r"\w+", text.lower())

    def build(self, captions_list):

        counter = Counter()

        for caps in captions_list:
            for cap in caps:
                counter.update(self.tokenize(cap))

        idx = 4

        for word, freq in counter.items():
            if freq >= self.freq_threshold:
                self.stoi[word] = idx
                self.itos[idx]  = word
                idx += 1

        print(f"Vocabulary size : {len(self.itos)} tokens")

    def numericalize(self, caption, max_len=50):

        tokens = [
            self.stoi.get(w, self.stoi['<UNK>'])
            for w in self.tokenize(caption)
        ]

        seq = (
            [self.stoi['<SOS>']] +
            tokens[:max_len - 2]  +
            [self.stoi['<EOS>']]
        )

        seq += [self.stoi['<PAD>']] * (max_len - len(seq))

        return seq

