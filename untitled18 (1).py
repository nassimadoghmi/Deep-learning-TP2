# Q4 : Fonctions train / validate + perplexité


criterion = nn.CrossEntropyLoss(ignore_index=0)


def train_caption_epoch(encoder, decoder, loader, optimizer, device):

    encoder.train()
    decoder.train()

    total_loss = 0

    for images, captions, lengths in tqdm(loader, leave=False):

        images   = images.to(device)
        captions = captions.to(device)

        # Teacher Forcing : on donne la vraie caption en entrée
        features = encoder(images)
        outputs  = decoder(features, captions, lengths)

        # Aligner sorties et cibles
        targets = captions[:, 1:]
        T = min(outputs.size(1), targets.size(1))

        loss = criterion(
            outputs[:, :T].reshape(-1, outputs.size(-1)),
            targets[:, :T].reshape(-1)
        )

        optimizer.zero_grad()
        loss.backward()

        # Gradient clipping
        nn.utils.clip_grad_norm_(decoder.parameters(), max_norm=5.0)

        optimizer.step()

        total_loss += loss.item()

    return total_loss / len(loader)


def validate_caption(encoder, decoder, loader, device):

    encoder.eval()
    decoder.eval()

    total_loss = 0

    with torch.no_grad():

        for images, captions, lengths in loader:

            images   = images.to(device)
            captions = captions.to(device)

            features = encoder(images)
            outputs  = decoder(features, captions, lengths)

            targets = captions[:, 1:]
            T = min(outputs.size(1), targets.size(1))

            loss = criterion(
                outputs[:, :T].reshape(-1, outputs.size(-1)),
                targets[:, :T].reshape(-1)
            )

            total_loss += loss.item()

    return total_loss / len(loader)

